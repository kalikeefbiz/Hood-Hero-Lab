import { z } from "zod";
const id = z.string().min(1),
  n = z.number().finite().nonnegative(),
  i = n.int(),
  zone = z.enum(["downtown", "rio", "south", "reservoir", "nawf"]),
  faction = z.enum(["angels", "backstreet", "blocks", "blips", "muds"]);
export const streetSchema = z.object({
  arrears: n,
  lots: z.array(
    z.object({
      id,
      category: z.literal("nightgoods"),
      owner: id,
      supplier: id,
      zone,
      received: i,
      remaining: i,
      lost: i,
      cost: n,
      expectedGross: n,
      collected: n,
      owed: n,
      paid: n,
      losses: n,
      crewPaid: n,
      dueDay: i,
      acquiredDay: i,
      arrangement: z.enum(["cash", "consignment"]),
      status: z.enum(["held", "distributed", "lost", "settled"]),
      agreementId: id.optional(),
    }),
  ),
  agreements: z.array(
    z.object({
      id,
      lotId: id,
      supplier: id,
      debtor: id,
      original: n,
      repaid: n,
      balance: n,
      dueDay: i,
      status: z.enum(["pending", "overdue", "fulfilled"]),
      commitmentId: id,
      history: z.array(id),
    }),
  ),
  transactions: z.array(
    z.object({
      id,
      day: i,
      lotId: id,
      market: zone,
      actor: id,
      partner: id.optional(),
      sold: i,
      lost: i,
      gross: n,
      loss: n,
      crewPaid: n,
      crewLoss: n,
      outcome: z.enum(["sale", "partial", "none", "money-loss", "goods-loss"]),
      eventId: id,
    }),
  ),
  markets: z.record(
    zone,
    z.object({
      zone,
      demand: n.max(100),
      pressure: n.max(100),
      competition: n.max(100),
      activity: n,
      actors: z.record(id, n),
      factions: z.partialRecord(faction, n),
      usedDay: i,
      used: i,
      lastDevelopmentDay: i,
    }),
  ),
  exposure: z.record(
    id,
    z.object({
      recent: z.array(z.object({ day: i, zone, weight: n })).max(30),
      investigation: n.max(100),
      warningBand: i,
    }),
  ),
  custody: z.array(
    z.object({
      id,
      character: id,
      arrestDay: i,
      cause: z.string(),
      severity: i,
      prior: i,
      releaseDay: i.nullable(),
      status: z.enum(["held", "released"]),
      conditions: z.string(),
      eventId: z.string(),
    }),
  ),
});
